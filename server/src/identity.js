// Анонимная личность игрока. В базу кладём tg_id (он нужен, чтобы узнать возвращающегося
// игрока), наружу не отдаём НИКОГДА: публично игрок — это «#<порядковый номер активации>
// <две буквы инициалов>». Ни username, ни ссылки, ни полного имени.
//
// Проект англоязычный, поэтому инициалы приводятся к латинице: кириллическое имя
// даёт «AS», а не «АС», и список читается одним алфавитом.

const CYR = {
  А: 'A', Б: 'B', В: 'V', Г: 'G', Д: 'D', Е: 'E', Ё: 'E', Ж: 'J', З: 'Z', И: 'I',
  Й: 'Y', К: 'K', Л: 'L', М: 'M', Н: 'N', О: 'O', П: 'P', Р: 'R', С: 'S', Т: 'T',
  У: 'U', Ф: 'F', Х: 'H', Ц: 'C', Ч: 'C', Ш: 'S', Щ: 'S', Ы: 'Y', Э: 'E', Ю: 'U',
  Я: 'Y', Ъ: '', Ь: '', І: 'I', Ї: 'I', Є: 'E', Ґ: 'G', Ә: 'A', Ө: 'O', Ұ: 'U', Қ: 'Q', Ң: 'N', Ғ: 'G', Һ: 'H',
};

const PLACEHOLDER = '?';

/** Одна буква профиля → один латинский знак верхнего регистра, либо ''. */
function latinize(ch) {
  const up = ch.toLocaleUpperCase();
  if (/^[A-Z0-9]$/.test(up)) return up;
  if (Object.hasOwn(CYR, up)) return CYR[up];
  // Любая другая письменность (китайский, арабский, иврит…) опознаваема, но не
  // латиница: отдаём заглушку, чтобы список оставался одноалфавитным.
  return /\p{L}|\p{N}/u.test(up) ? PLACEHOLDER : '';
}

function lettersOf(s, take) {
  const out = [];
  for (const ch of String(s ?? '')) {
    const l = latinize(ch);
    if (l) { out.push(l); if (out.length === take) break; }
  }
  return out.join('');
}

/**
 * Две буквы инициалов: имя + фамилия, иначе две первых буквы имени, иначе
 * буква + «?», иначе «??». Ровно два знака — чтобы список выглядел ровно.
 */
export function initialsFrom(user = {}) {
  const f = lettersOf(user.first_name, 1);
  const l = lettersOf(user.last_name, 1);
  let ii = f && l ? f + l : lettersOf(user.first_name, 2);
  if (ii.length === 1) ii += PLACEHOLDER;
  if (!ii) ii = PLACEHOLDER + PLACEHOLDER;
  return ii.slice(0, 2);
}

/** Публичный ярлык: «#43 AS». Единственная форма, в которой игрок виден другим. */
export function publicHandle(seq, initials) {
  return `#${seq} ${initials}`;
}

/**
 * Границы правдоподобия счёта. Выведены из физики движка, а не взяты с потолка,
 * и сверяются с ней тестом (tests/plausibility.test.js) — иначе изменение игры
 * начнёт молча отбивать честные забеги.
 *
 * Пара блокеров приходит не чаще, чем раз в 0.806 с (интервал 250 px при максимальной
 * скорости 310 px/s). За эту пару игрок берёт максимум 10 очков за блокер плюс 5 за
 * монету, и при активном множителе всё идёт вдвойне: 30 очков за 0.806 с, то есть
 * ~27 мс на очко в абсолютном пределе. Ставим 20 мс — ниже предела с запасом, чтобы
 * не наказать за рывок.
 *
 * Порог живёт здесь, а цены очков — в движке игры. Это два разных образа, поэтому
 * согласованность проверяется тестом, который выводит предел из констант движка заново.
 */
export const MIN_MS_PER_POINT = 20;
/** ≈5 минут безупречной игры со всеми бонусами. Выше этого — уже не человек. */
export const MAX_PLAUSIBLE_SCORE = 15_000;
export function sanitizeScore(raw) {
  // Строго число, без приведения: в JSON счёт объявлен числом, и строка "42"
  // здесь означает странного клиента, а не валидные данные. Молча коэрцить —
  // значит прятать поломку клиента и заодно расширять поверхность накрутки.
  if (typeof raw !== 'number') return null;
  if (!Number.isInteger(raw) || raw < 0 || raw > MAX_PLAUSIBLE_SCORE) return null;
  return raw;
}
